const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { AudioHost } = require('../src/audio-host.cjs');
const { Chains } = require('../src/chains.cjs');
const directory = path.resolve('.local/chain-regression-' + Date.now());
const exe = path.resolve('native/build/MizuAudioHost_artefacts/Release/MizuAudioHost.exe');
let host;
(async () => {
  host = new AudioHost(exe); await host.ensureReady();
  let chains = new Chains(directory, host);
  const plugin = 'C:\\Program Files\\Common Files\\VST3\\Bevel EQ.vst3';
  host.command(2, plugin); host.command(2, plugin);
  let state = await chains.snapshot(); assert.equal(state.length, 2); assert.ok(state[0].state.length > 20);
  host.command(5, String(host.plugins[0].id));
  await chains.save('Test preset');
  state = chains.data.last;
  assert.equal(state[0].bypass, true); assert.equal(state[1].bypass, false);
  host.command(9); await chains.snapshot(); assert.equal(host.plugins.length, 0);
  await chains.load(chains.list()[0].id);
  assert.deepEqual(await chains.snapshot(), state);
  await chains.capture(); host.stop();
  host = new AudioHost(exe); await host.ensureReady();
  chains = new Chains(directory, host); await chains.restore(chains.data.last);
  assert.deepEqual(await chains.snapshot(), state);
  await assert.rejects(chains.restore([{ ...state[0], path: path.resolve('.local/missing.vst3') }]));
  await chains.capture(); assert.deepEqual(chains.data.last, state);
  assert.equal(JSON.parse(fs.readFileSync(chains.file)).presets.length, 1);
  console.log('PRESETS: state/bypass/order round-trip, host restart, missing-plugin protection passed');
})().catch(error => { console.error(error); process.exitCode = 1; }).finally(() => host?.stop());
